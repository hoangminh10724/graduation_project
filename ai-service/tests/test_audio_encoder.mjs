import assert from 'node:assert/strict';
import {encodeWav, sampleLevels, gainSamples} from '../app/demo_static/audio.mjs';
const blob = encodeWav(new Float32Array([-2, -1, 0, 1, 2]));
const bytes = await blob.arrayBuffer();
const view = new DataView(bytes);
assert.equal(blob.type, 'audio/wav');
assert.equal(view.getUint32(24, true), 16000);
assert.equal(view.getUint16(22, true), 1);
assert.equal(view.getUint32(40, true), 10);
assert.deepEqual([0,1,2,3,4].map(i => view.getInt16(44 + i * 2, true)), [-32768,-32768,0,32767,32767]);
const original = [-32000,-16385,-1,0,1,16385,30000];
const roundtrip = new DataView(await encodeWav(new Float32Array(original.map(x=>x/32768))).arrayBuffer());
assert.deepEqual(original.map((_,i)=>roundtrip.getInt16(44+i*2,true)),original);
assert.deepEqual(sampleLevels(new Float32Array()), {peak:0,rms:0,clippingFraction:0});
assert.equal(sampleLevels(new Float32Array([-.25,.25])).peak,.25);
assert.equal(sampleLevels(new Float32Array([-.25,.25])).rms,.25);
assert.equal(sampleLevels(new Float32Array([0,1,-1,0])).clippingFraction,.5);
const raw = new Float32Array([-.01, .01]);
const raised = gainSamples(raw, 8);
assert.ok(Math.abs(sampleLevels(raised).peak / sampleLevels(raw).peak - 8) < 1e-6);
assert.deepEqual([...raw], [...new Float32Array([-.01,.01])]);
assert.deepEqual([...gainSamples(raw, 1)], [...raw]);
assert.throws(() => gainSamples(raw, 0));
assert.throws(() => gainSamples(raw, Infinity));
console.log('PCM-16 WAV encoding, clipping and level-meter checks passed.');
